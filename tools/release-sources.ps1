$root = [IO.Path]::GetFullPath($ProjectRoot)
$prefix = $root.TrimEnd('\') + '\'
$catalog = Get-Content -LiteralPath (Join-Path $root 'locales/languages.json') -Encoding UTF8 -Raw | ConvertFrom-Json
$catalogFiles = @($catalog.languages | ForEach-Object { 'locales/' + $_.tag + '.json' })
$seen = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
foreach ($name in $files + $catalogFiles) {
    if (!$seen.Add($name)) { throw "Duplicate source-package entry: $name" }
    if ([IO.Path]::IsPathRooted($name) -or $name -match '[:\\]|//|(^|/)(\.{1,2}|work|outputs|Releases|node_modules|target|gen)(/|$)|\.(exe|dll|lnk|log|env)$') {
        throw "Non-source file in package: $name"
    }
    $path = [IO.Path]::GetFullPath((Join-Path $root $name))
    if (!$path.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase) -or ![IO.File]::Exists($path)) {
        throw "Missing or out-of-root source: $name"
    }
    $name
}
